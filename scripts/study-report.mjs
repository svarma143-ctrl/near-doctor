// Aggregates a scripts/study.mjs run into docs/STUDY.md (counts only; no repository names are published).
//   node scripts/study-report.mjs /path/to/study/results.jsonl > docs/STUDY.md
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_RULES_DIR, loadRules } from "../src/index.mjs";

const file = process.argv[2];
if (!file) {
  console.error("usage: study-report.mjs RESULTS.jsonl");
  process.exit(2);
}
const rows = fs.readFileSync(file, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
const ok = rows.filter((r) => !r.error);
const rules = new Map(loadRules(DEFAULT_RULES_DIR).map((r) => [r.id, r]));
const byLang = (lang) => ok.filter((r) => r.language === lang);
const langs = [...new Set(ok.map((r) => r.language))].sort();

const perRule = new Map();
for (const r of ok) {
  for (const f of r.findings) {
    const e = perRule.get(f.id) || { findings: 0, repos: new Set(), langs: new Set() };
    e.findings++;
    e.repos.add(r.repo);
    e.langs.add(r.language);
    perRule.set(f.id, e);
  }
}
const nonHistorical = new Set(ok.filter((r) => r.findings.some((f) => rules.get(f.id)?.status !== "historical")).map((r) => r.repo));
const scope = (id) => ({ "F-004": "Rust", "F-012": "Rust", "F-005": "Rust", "F-006": "JavaScript/TypeScript", "F-001": "Rust", "F-008": "any", "F-007": "JavaScript/TypeScript (needs node_modules)" })[id] || "";
const denom = (id) => {
  const s = scope(id);
  if (s === "Rust") return byLang("Rust").length;
  if (s.startsWith("JavaScript")) return ok.filter((r) => r.language !== "Rust").length;
  return ok.length;
};

const L = [];
L.push("# Study: near-doctor's static rules on public hackathon repositories", "");
L.push("Generated by `scripts/study-report.mjs` from a `scripts/study.mjs` run. Counts only; no repository is named.", "");
L.push("## Method", "");
L.push(`- ${rows.length} public GitHub repositories whose README mentions "NEAR HACKATHON", created after 19 Oct 2026, found with the unauthenticated GitHub search API, ${langs.map((l) => `${byLang(l).length} ${l}`).join(", ")}. Forks, archived repos and repos over 30 MB were skipped. ${rows.length - ok.length} repositories failed to download.`);
L.push("- Each repository was downloaded as a source tarball and scanned **statically** by near-doctor (no project code was executed or compiled). Historical rules were included so they could be counted separately.");
L.push("- The rules were audited by reading the flagged source in a random sample of hits, and **corrected four times** (one rule each) during this study (see \"What the study changed\"). The numbers below are from the corrected rules.", "");
L.push("## Results", "");
L.push("| Rule | What it finds | Repos flagged | Findings | Meaning |", "| --- | --- | --- | --- | --- |");
const meaning = {
  "F-004": "has a `#[near]` method with more than 7 parameters and no allow, so clippy warns on the generated wrapper",
  "F-005": "pattern only: `.max_gas()` plus balance reads plus an assert in one test file. Not shown to fail",
  "F-006": "`Account.callFunction[Raw]` plus `Failure` inspection without `throwOnFailure: false` (near-api-js v7 throws first)",
  "F-012": "test file uses a crate its Cargo.toml does not declare",
  "R-001": "historical: the old `PrepareError(Deserialization)` build pattern; does not reproduce today and is never a warning",
};
for (const [id, e] of [...perRule.entries()].sort()) {
  const d = denom(id);
  L.push(`| ${id} | ${rules.get(id)?.title ?? ""} | ${e.repos.size} of ${d} (${Math.round((100 * e.repos.size) / d)}%) ${scope(id) ? scope(id) + " repos" : ""} | ${e.findings} | ${meaning[id] ?? ""} |`);
}
for (const id of ["F-001", "F-007", "F-008", "F-012"]) {
  if (!perRule.has(id)) {
    const why = id === "F-007" ? "cannot run on tarballs: it needs installed `node_modules`" : "0 hits: this breaks the build, so authors fix it before publishing";
    L.push(`| ${id} | ${rules.get(id)?.title ?? ""} | 0 of ${denom(id)} | 0 | ${why} |`);
  }
}
L.push("", `${nonHistorical.size} of ${ok.length} repositories (${Math.round((100 * nonHistorical.size) / ok.length)}%) have at least one non-historical finding (F-005 is only a pattern match).`, "");
L.push("## What the study does and does not show", "");
L.push("- It is a convenience sample of hackathon repos, not a random sample of NEAR code. It shows that these patterns occur in real code; it does not estimate how common they are in general.");
L.push("- A finding is a source-level match. Flagged repos were not compiled, because building a stranger's repository runs its build scripts. The underlying behavior of F-004 was reproduced on a fixture with `cargo near check --clippy`.");
L.push("- Build-breaking problems (F-001, F-008) have no hits because published code has already been fixed. Those rules help while writing code, not when auditing finished repos.");
L.push("- Precision was checked by hand on a sample of hits (reading the raw source), not measured on the full set.", "");
L.push("## What the study changed", "");
L.push("The first version of the rules had false positives that unit tests and fixtures did not catch:", "");
L.push("1. F-004 flagged methods that already carry `#[allow(clippy::too_many_arguments)]`. Testing showed a method-level allow silences the wrapper, an impl-level allow does not. (79 findings in 41 repos dropped to 28 in 21.)");
L.push("2. F-012 checked a nested crate's test files against the root `Cargo.toml`, treated virtual workspace roots as crates, and flagged files Cargo never compiles. (8 findings dropped to 0.)");
L.push("3. F-005 fired on any file that mentioned `balance`; it now needs a balance read and an assert, ignores the `.balance(..)` builder, and is `info`.");
L.push("4. F-006 fired on read-only `provider.callFunction[Raw]` calls and on identifiers that contain the word `Failure`; it now needs near-api-js, an Account receiver and the whole word.", "");
process.stdout.write(L.join("\n") + "\n");
